"""Turn ARM's DAP_SWD_Transfer into a macro, so it can be expanded once per clock path.

`DAP_SWD_Transfer` calls `SWD_Transfer` once per transfer, and `SWD_Transfer` chooses between the
paced and delay-free copies on every call. Expanding the command next to each copy lets the
transfer inline into it, which pays a transfer's register prologue once per command rather than
once per transfer. `src/swd_dp.c` does the same thing for the block command.

This is a generator rather than a transcription because `external/CMSIS-DAP` is a pinned submodule
that will be bumped. Re-run it after a bump and diff the result:

    uv run tools/extract_swd_transfer.py

Four things have to change on the way through, and all four are why this is not a copy:

- The five `#if (TIMESTAMP_CLOCK != 0U)` blocks cannot survive inside a macro. They are resolved
  by keeping the bodies, and the generated header asserts the condition instead.
- `//` comments swallow the line continuation, so they become `/* */`.
- Every `SWD_Transfer(...)` call becomes `xfer(...)`, the macro's parameter.
- `data` gains an initialiser. Once the transfer inlines into this function, GCC can no longer
  prove the variable is written on every path, and a build without link-time optimisation fails
  on `-Wmaybe-uninitialized`. ARM's own build never sees it because the transfer stays a call.
- Every line gains a trailing backslash.
"""

import re
import sys
from pathlib import Path

SOURCE = Path("external/CMSIS-DAP/Firmware/Source/DAP.c")
TARGET = Path("src/swd_transfer.h")
WIDTH = 108

BANNER = '''/*
 * Copyright (c) 2013-2022 ARM Limited. All rights reserved.
 * SPDX-License-Identifier: Apache-2.0
 *
 * From CMSIS-DAP, DAP.c's DAP_SWD_Transfer. Changed by the Escapement Project: made a macro, with
 * the timestamp blocks resolved.
 */
/** ARM's DAP_SWD_Transfer as a macro, so each clock path gets its own copy.
 *
 * GENERATED by tools/extract_swd_transfer.py from
 * {source}. Do not edit: re-run the
 * generator after bumping the submodule and diff the result.
 *
 * `xfer` is the transfer to call, which is how the paced and delay-free copies are kept apart.
 * The caller is responsible for the packet parity: `SWD_Transfer{{Fast,Slow}}` take it in bit 6,
 * and `SWD_WithParity` puts it there. See src/swd_dp.c.
 */
#ifndef SWD_TRANSFER_H
#define SWD_TRANSFER_H

#include "DAP_config.h"

#include "DAP.h"

/* The generator resolved five `#if (TIMESTAMP_CLOCK != 0U)` blocks by keeping their bodies, so
 * the generated code is only correct while that holds. */
static_assert(TIMESTAMP_CLOCK != 0U, "swd_transfer.h was generated with timestamps enabled");

#define SWD_TRANSFER_FUNCTION(name, xfer) \\
'''

FOOTER = "\n#endif\n"


def extract(text: str) -> list[str]:
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("static uint32_t DAP_SWD_Transfer"))
    end = next(i for i in range(start, len(lines)) if lines[i] == "}")
    return lines[start : end + 1]


def transform(lines: list[str]) -> list[str]:
    out = []
    dropped = 0
    calls = 0
    comments = 0
    initialised = 0
    for line in lines:
        stripped = line.strip()
        if stripped == "#if (TIMESTAMP_CLOCK != 0U)" or stripped == "#endif":
            dropped += 1
            continue
        # A // comment would eat the backslash that continues the macro.
        m = re.match(r"^(.*?)//\s?(.*)$", line)
        if m and "://" not in line:
            body, comment = m.group(1), m.group(2).rstrip()
            line = f"{body}/* {comment} */" if comment else body.rstrip()
            comments += 1
        before = line
        line = re.sub(r"\bSWD_Transfer\(([^,]+),", r"xfer(\1,", line)
        if line != before:
            calls += 1
        if re.fullmatch(r"\s*uint32_t\s+data;", line):
            line = line.replace("data;", "data = 0U;")
            initialised += 1
        line = re.sub(r"\bNULL\b", "nullptr", line)
        out.append(line.rstrip())
    out[0] = out[0].replace(
        "static uint32_t DAP_SWD_Transfer(const uint8_t *request, uint8_t *response) {",
        "static uint32_t name(const uint8_t *request, uint8_t *response) {",
    )
    print(
        f"  {dropped} preprocessor lines resolved, {comments} comments converted,"
        f" {calls} calls rerouted, {initialised} declaration initialised"
    )
    if initialised != 1:
        sys.exit(f"expected one `uint32_t data;` to initialise, found {initialised}")
    if "name(" not in out[0]:
        sys.exit(f"the signature did not match: {out[0]!r}")
    if calls == 0:
        sys.exit("no SWD_Transfer calls were rerouted, which cannot be right")
    return out


def main() -> int:
    if not SOURCE.exists():
        sys.exit(f"{SOURCE} not found; run from the repository root")
    body = transform(extract(SOURCE.read_text()))
    padded = [f"{line:<{WIDTH}}\\" if line else " " * WIDTH + "\\" for line in body]
    padded[-1] = body[-1]  # the last line of a macro takes no continuation
    TARGET.write_text(BANNER.format(source=SOURCE) + "\n".join(padded) + FOOTER)
    print(f"  wrote {TARGET}, {len(body)} lines of macro")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
