#ifndef DAP_CORE_SECURITY_H
#define DAP_CORE_SECURITY_H

#include <stdint.h>

enum {
    USB_SECURITY_AHB_PORT8_SLAVE0_RULE = 0x120U / 4U,
    USB_SECURITY_AHB_PORT8_SLAVE1_RULE = 0x124U / 4U,
    USB_SECURITY_AHB_PORT9_SLAVE0_RULE = 0x130U / 4U,
    USB_SECURITY_USB_HS_SLAVE_RULE = 0x160U / 4U,
    USB_SECURITY_USB_HS_MEM_RULE = 0x170U / 4U,
    USB_SECURITY_MASTER_SEC_LEVEL = 0xFD0U / 4U,
    USB_SECURITY_MASTER_SEC_ANTI_POL = 0xFD4U / 4U,
};

#define USB_SECURITY_RULE_NS_PRIV 0x1U
#define USB_SECURITY_USB_RAM_RULE_MASK 0x3U
#define USB_SECURITY_USB_RAM_SECTIONS_MASK 0x3333U
#define USB_SECURITY_USB_RAM_SECTIONS_NS_PRIV 0x1111U
#define USB_SECURITY_CPU1_MASTER_LEVEL_MASK (0x3U << 4 | 0x3U << 6)
#define USB_SECURITY_CPU1_MASTER_LEVEL_NS_PRIV (0x1U << 4 | 0x1U << 6)
#define USB_SECURITY_CPU1_MASTER_ANTI_POL_MASK USB_SECURITY_CPU1_MASTER_LEVEL_MASK
#define USB_SECURITY_CPU1_MASTER_ANTI_POL_NS_PRIV \
    ((~USB_SECURITY_CPU1_MASTER_LEVEL_NS_PRIV) & USB_SECURITY_CPU1_MASTER_ANTI_POL_MASK)
/** DMA0, which fetches its descriptor table from USB SRAM and writes SWO trace there, and whose
 *  rules there admit privileged masters only. */
#define USB_SECURITY_DMA0_MASTER_LEVEL_MASK (0x3U << 10)
#define USB_SECURITY_DMA0_MASTER_LEVEL_NS_PRIV (0x1U << 10)
#define USB_SECURITY_DMA0_MASTER_ANTI_POL_NS_PRIV \
    ((~USB_SECURITY_DMA0_MASTER_LEVEL_NS_PRIV) & USB_SECURITY_DMA0_MASTER_LEVEL_MASK)
/** Every master level this file sets, and the matching anti-polarity bits. */
#define USB_SECURITY_MASTER_LEVEL_MASK (USB_SECURITY_CPU1_MASTER_LEVEL_MASK | USB_SECURITY_DMA0_MASTER_LEVEL_MASK)
#define USB_SECURITY_MASTER_LEVEL_NS_PRIV \
    (USB_SECURITY_CPU1_MASTER_LEVEL_NS_PRIV | USB_SECURITY_DMA0_MASTER_LEVEL_NS_PRIV)
#define USB_SECURITY_MASTER_ANTI_POL_NS_PRIV \
    (USB_SECURITY_CPU1_MASTER_ANTI_POL_NS_PRIV | USB_SECURITY_DMA0_MASTER_ANTI_POL_NS_PRIV)
#define USB_SECURITY_MASTER_DEFINED_MASK 0xC3FF0FF0U

/** Give CPU1 DAP code access to shared packet RAM, and set both CPU1 bus masters and DMA0 to NS
 *  privileged. */
static inline void dap_core_security_apply(volatile uint32_t* registers) {
    uint32_t value = registers[USB_SECURITY_USB_HS_SLAVE_RULE];
    registers[USB_SECURITY_USB_HS_SLAVE_RULE] =
        (value & ~USB_SECURITY_USB_RAM_RULE_MASK) | USB_SECURITY_RULE_NS_PRIV;

    value = registers[USB_SECURITY_USB_HS_MEM_RULE];
    registers[USB_SECURITY_USB_HS_MEM_RULE] =
        (value & ~USB_SECURITY_USB_RAM_SECTIONS_MASK) | USB_SECURITY_USB_RAM_SECTIONS_NS_PRIV;

    value = registers[USB_SECURITY_MASTER_SEC_LEVEL];
    registers[USB_SECURITY_MASTER_SEC_LEVEL] =
        (value & USB_SECURITY_MASTER_DEFINED_MASK & ~USB_SECURITY_MASTER_LEVEL_MASK) |
        USB_SECURITY_MASTER_LEVEL_NS_PRIV;

    value = registers[USB_SECURITY_MASTER_SEC_ANTI_POL];
    registers[USB_SECURITY_MASTER_SEC_ANTI_POL] =
        (value & USB_SECURITY_MASTER_DEFINED_MASK & ~USB_SECURITY_MASTER_LEVEL_MASK) |
        USB_SECURITY_MASTER_ANTI_POL_NS_PRIV;
}

#endif
